"""macOS offline TTS demo. Word durations estimate timing; NOT forced alignment."""
from pathlib import Path
import array
import json
import subprocess
import tempfile
import wave
ROOT = Path(__file__).resolve().parent.parent
WORDS = 'The little girl opened the wooden door and discovered a beautiful garden behind the house'.split()
VOICE = 'Samantha'
RATE = 170

def synth(text, target):
    subprocess.run(['say', '-v', VOICE, '-r', str(RATE), '-o', str(target), '--data-format=LEI16@22050', text], check=True)

def bounds(path):
    with wave.open(str(path)) as audio:
        sr = audio.getframerate()
        samples = array.array('h', audio.readframes(audio.getnframes()))
    active = [i for i, value in enumerate(samples) if abs(value) > 180]
    if not active:
        raise RuntimeError('TTS output is empty or silent. Run with access to macOS speech services.')
    return active[0] / sr, (active[-1] + 1) / sr, len(samples) / sr

out = ROOT / 'public/audio/stage-01-synthetic.wav'
synth(' '.join(WORDS) + '.', out)
first, last, duration = bounds(out)
weights = []
with tempfile.TemporaryDirectory(prefix='rhythm-tts-') as folder:
    for i, word in enumerate(WORDS):
        path = Path(folder) / f'{i}.wav'
        synth(word, path)
        a, b, _ = bounds(path)
        weights.append(max(.06, b-a))
# Normalize isolated-word durations to the full utterance. Coarticulation and
# phrase stress differ: these estimates must never be marked measured/verified.
scale = (last-first) / sum(weights)
starts = []
cursor = first
for weight in weights:
    starts.append(round(cursor, 4))
    cursor += weight * scale
metadata = {'stageId':'stage-01', 'voice':VOICE, 'locale':'en-US', 'wordsPerMinute':RATE,
            'audioFile':'stage-01-synthetic.wav', 'duration':duration,
            'timingStatus':'estimated-not-aligned', 'verified':False,
            'method':'Isolated-word voiced durations scaled to full-sentence voiced interval; not measured word onsets.',
            'words':[{'text':word, 'start':start} for word, start in zip(WORDS, starts)]}
(ROOT / 'public/audio/stage-01-synthetic.json').write_text(json.dumps(metadata, indent=2)+'\n')
(ROOT / 'src/synthetic-demo.js').write_text('// Generated by scripts/generate-synthetic-audio.py; estimated onsets, NOT measured.\n'
    + 'export const syntheticDemos = {\n  "stage-01": {\n'
    + '    audio: new URL("../public/audio/stage-01-synthetic.wav", import.meta.url).href,\n'
    + '    verified: false, timingStatus: "estimated-not-aligned",\n'
    + '    starts: '+json.dumps(starts)+'\n  }\n};\n')
print(json.dumps({'duration':duration, 'estimatedStarts':starts}))
